def page_path(card_id: str, language: str) -> Path:
    return CONTENT / f"taskcard.{card_id}.v4.{language}.md"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--facts", type=Path, metavar="BUNDLE", help="write cards/<slug>/card.json from this built bundle")
    parser.add_argument("--card", help="with --facts: the expected scenario slug of the bundle")
    parser.add_argument("--pages", action="store_true", help="write the card pages from cards/*/card.json")
    parser.add_argument("--check-pages", action="store_true", help="fail if a committed page differs from its card.json")
    args = parser.parse_args()
    if args.facts:
        f = bundle_facts(args.facts)
        if args.card and f["slug"] != args.card:
            parser.error(f"{args.facts} is card {f['slug']}, not {args.card}")
        if f["card_id"] not in SYMBOLS or f["phase"] != "practice-projects":
            parser.error(f"{args.facts} is not a practice card ({f['card_id']}, {f['phase']})")
        path = CARDS / f["slug"] / "card.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(f, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(path.relative_to(ROOT).as_posix())
        return 0
    if not (args.pages or args.check_pages):
        parser.error("one of --facts, --pages, --check-pages is required")
    stale = []
    for card_json in card_files().values():
        card_id = facts(card_json)["card_id"]
        for language in ("en", "zh"):
            text, path = render_page(card_json, language), page_path(card_id, language)
            if args.pages:
                path.write_text(text, encoding="utf-8")
            elif not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
    if stale:
        print("stale card pages (run --pages):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
