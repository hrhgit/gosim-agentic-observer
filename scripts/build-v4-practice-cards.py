#!/usr/bin/env python3
"""The v4 PRACTICE cards (Practice α β γ δ): their facts and their pages.

    python3 scripts/build-v4-practice-cards.py --facts BUNDLE --card v4-practice-alpha  # write cards/<slug>/card.json
    python3 scripts/build-v4-practice-cards.py --pages          # (re)write web/src/content/taskcard.<id>.v4.*.md
    python3 scripts/build-v4-practice-cards.py --check-pages    # exit 1 if a page differs from its card.json

The practice cards are generated by the organizers from secret seeds; the generator inputs are not
in this repository. Their bundles are fully public once registered (config/, public/ and truth/ in
the 'scenarios' bucket), so participants download the files from the Resources page. What this
repository keeps per card is cards/<slug>/card.json: the facts a card page states (site, season,
nights, targets, regions, fibres, score zero points), read from the registered bundle with --facts,
plus the manifest checksum of that bundle (public.scenarios.checksum). No seed is read or written.

The card pages are rendered from web/src/content/taskcard.template.v4.<lang>.md with those facts and
the per-card story below, so a page can never disagree with its card (tests/test_v4_practice_cards.py
checks it).

Registration (organizer): scenario slug = the card's scenario_slug, contract 'v4-score-v1',
weather/forecasts/events public, global_wallclock_seconds 900; the bundle ZIP as its evaluation
bundle; config/, public/ and truth/ in the public 'scenarios' bucket under <slug>/; parked in the
sealed staging phase until it is linked to practice-projects with its files released.
"""
