# The template states these score rules in words; a card that changes them needs new wording.
FIXED_RULES = {("program", "multipliers"): {"DARK": 1.2, "BRIGHT": 1.12, "BACKUP": 1.06},
               ("required", "penalty_per_missing"): 50, ("required", "observed_factor_threshold"): 0.5,
               ("uniformity", "weight"): 200.0, ("reporting", "correct_reward"): 100, ("reporting", "false_penalty"): -150}


def card_files() -> dict[str, Path]:
    """cards/<slug>/card.json of every practice card, by slug."""
    return {path.parent.name: path for path in sorted(CARDS.glob("v4-practice-*/card.json"))}


def facts(card_json: Path) -> dict:
    """What a card page states: cards/<slug>/card.json plus the values derived from it."""
    f = json.loads(card_json.read_text(encoding="utf-8"))
    side = math.isqrt(int(f["fibers"]))
    if side * side != int(f["fibers"]):
        raise ValueError(f"{card_json}: the page wording assumes a square grid")
    return {**f, "grid": side, "field_area": round(int(f["fibers"]) * float(f["fiber_area"]), 6),
            "exposure": tuple(f["exposure"])}


def _rows(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _footprint_area(root: Path) -> float:
    by: dict[str, list] = {}
    for r in _rows(root / "public" / "footprint.csv"):
        by.setdefault(r["component_id"], []).append((int(r["vertex_index"]), float(r["ra_deg"]), float(r["dec_deg"])))
    total = 0.0
    for verts in by.values():
        pts = [(ra, dec) for _, ra, dec in sorted(verts)]
        units = [v4_catalog_generator._unit_vector(ra, dec) for ra, dec in pts]
        c = v4_catalog_generator._normalize(tuple(sum(v[i] for v in units) for i in range(3)))
        centre = (math.degrees(math.atan2(c[1], c[0])) % 360, math.degrees(math.asin(c[2])))
        total += v4_catalog_generator._polygon_area_deg2(centre, tuple(pts))
    return total


def bundle_facts(root: Path) -> dict:
    """card.json content read from a built bundle (config/, public/; nothing from truth/ but the checksum)."""
    load = lambda rel: json.loads((root / rel).read_text(encoding="utf-8"))  # noqa: E731
    scenario, fiber, score = load("config/v4_scenario.json"), load("config/v4_fiber_config.json"), load("config/v4_score_config.json")
    for keys, expected in FIXED_RULES.items():
        value = score[keys[0]][keys[1]]
        if value != expected:
            raise ValueError(f"{root}: score {'.'.join(keys)} is {value!r}; the page template assumes {expected!r}")
    field = fiber["field"]
    if float(field["gap_deg"]) != 0.0:
        raise ValueError(f"{root}: the page wording assumes fibre cells without gaps")
    nights, targets = _rows(root / "public" / "v4_night_calendar.csv"), _rows(root / "public" / "targets.csv")
    files = sorted(p for p in root.rglob("*") if p.is_file())
    manifest = {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    site = scenario["site"]
    return {
        "card_id": scenario["task_card"]["card_id"], "slug": scenario["task_card"]["scenario_slug"],
        "phase": scenario["task_card"]["phase"], "stress": bool(scenario["stress"]["enabled"]),
        "wallclock": int(scenario["limits"]["global_wallclock_seconds"]),
        "site": {k: site[k] for k in ("name", "latitude_deg", "longitude_deg")},
        "first_night": nights[0]["night_date"], "last_night": nights[-1]["night_date"], "nights": len(nights),
        "targets": len(targets), "required": sum(r["required"] == "true" for r in targets),
        "regions": len({r["component_id"] for r in _rows(root / "public" / "footprint.csv")}),
        "area": round(_footprint_area(root), -1),
        "sun_limit": float(site.get("sun_altitude_limit_deg", -18.0)), "min_alt": float(scenario["minimum_altitude_deg"]),
        "fibers": int(field["n_fibers"]), "fiber_area": float(field["fiber_area_deg2"]),
        "exposure": [int(fiber["exposure"]["min_duration_seconds"]), int(fiber["exposure"]["max_duration_seconds"])],
        "f0": float(score["flux_zero_point"]), "t0": float(score["exposure_zero_point_seconds"]),
        "checksum": hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest(),
    }


# ------------------------------------------------------------------ pages
def _num(value: float, digits: int = 0) -> str:
    return f"{value:,.{digits}f}"


def _deg(value: float) -> str:
    return f"{value:+.2f}°".replace("+", "" if value >= 0 else "").replace("-", "−")


def _swap(text: str, old: str, new: str) -> str:
    if old not in text:
        raise ValueError(f"template text changed; cannot find {old[:60]!r}")
    return text.replace(old, new)


